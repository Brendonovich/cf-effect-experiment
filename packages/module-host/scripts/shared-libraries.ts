import { SharedLibraries } from "@macrograph/module/SharedLibraries";
import { existsSync, readdirSync, readFileSync, realpathSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

/**
 * Subpaths matched by a server wildcard that are build tooling rather than runtime libraries.
 * Leaving them out keeps their dependencies (Babel, magic-string) out of the server bundle.
 */
export const serverExcluded: ReadonlyArray<string> = ["@macrograph/module/vite"];

export const outputFile = fileURLToPath(
  new URL("../src/SharedLibraryTable.generated.ts", import.meta.url),
);

const packageRoot = fileURLToPath(new URL("..", import.meta.url));
const require = createRequire(join(packageRoot, "package.json"));

const walk = (directory: string): Array<string> =>
  readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) return entry.name === "node_modules" ? [] : walk(path);
    return entry.isFile() ? [path] : [];
  });

const toPosix = (path: string) => path.split(sep).join("/");

/** Every specifier a package's `exports` field resolves, with wildcards expanded against its files. */
const exportedSpecifiers = (packageName: string): Array<string> => {
  const lookup = (require.resolve.paths(packageName) ?? [])
    .map((nodeModules) => join(nodeModules, packageName, "package.json"))
    .find((path) => existsSync(path));
  if (lookup === undefined) throw new Error(`Cannot find ${packageName}`);
  const manifestPath = realpathSync(lookup);
  const directory = dirname(manifestPath);
  const manifest: unknown = JSON.parse(readFileSync(manifestPath, "utf8"));
  const exportsField =
    typeof manifest === "object" && manifest !== null && "exports" in manifest
      ? manifest.exports
      : undefined;
  if (typeof exportsField !== "object" || exportsField === null)
    throw new Error(`${packageName} has no exports map`);

  const files = walk(directory).map((file) => `./${toPosix(relative(directory, file))}`);
  const candidates = new Map<string, string>();
  for (const [key, target] of Object.entries(exportsField)) {
    if (target === null) continue;
    if (typeof target !== "string")
      throw new Error(`${packageName}: conditional export "${key}" is not supported`);
    const subpath = key === "." ? "" : key.slice(1);
    if (!key.includes("*")) {
      candidates.set(`${packageName}${subpath}`, join(directory, target));
      continue;
    }
    const [keyPrefix = "", keySuffix = ""] = subpath.split("*");
    const [targetPrefix = "", targetSuffix = ""] = target.split("*");
    for (const file of files) {
      if (!file.startsWith(targetPrefix) || !file.endsWith(targetSuffix)) continue;
      const middle = file.slice(targetPrefix.length, file.length - targetSuffix.length);
      if (middle.length === 0) continue;
      candidates.set(`${packageName}${keyPrefix}${middle}${keySuffix}`, join(directory, file));
    }
  }

  // Keep a specifier only if Node resolves it to the file it was expanded from. This applies
  // the `null` exclusions and pattern precedence exactly as Node does.
  return [...candidates]
    .filter(([specifier, file]) => {
      if (specifier.endsWith("/package.json")) return false;
      try {
        return require.resolve(specifier) === file;
      } catch {
        return false;
      }
    })
    .map(([specifier]) => specifier);
};

export const specifiers = (): ReadonlyArray<string> => {
  const packages = [...new Set(SharedLibraries.server.map(SharedLibraries.packageName))];
  return packages
    .flatMap(exportedSpecifiers)
    .filter(
      (specifier) =>
        SharedLibraries.isShared(specifier, "server") && !serverExcluded.includes(specifier),
    )
    .sort((left, right) => (left < right ? -1 : left > right ? 1 : 0));
};

export const generate = (): string => {
  const list = specifiers();
  const imports = list.map((specifier, index) => `import * as m${index} from "${specifier}";`);
  const entries = list.map((specifier, index) => `  ["${specifier}", m${index}],`);
  return [
    "// Generated by scripts/generate-shared-libraries.ts from SharedLibraries.server and the",
    "// exports of each shared package. Do not edit by hand; run `pnpm generate` instead.",
    ...imports,
    "",
    "export const table: ReadonlyMap<string, unknown> = new Map<string, unknown>([",
    ...entries,
    "]);",
    "",
  ].join("\n");
};

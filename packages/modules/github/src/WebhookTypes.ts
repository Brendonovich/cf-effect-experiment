import { DataType } from "@macrograph/module";

const id = (name: string) => DataType.DefinitionId.make(`github/${name}`);
const custom = (name: string) => DataType.Custom(id(name));
const option = (type: DataType.Any) => DataType.Option(type);
type Field = typeof DataType.Field.Type;
const field = (name: string, type: DataType.Any): Field => ({ name, type });
const struct = (name: string, fields: ReadonlyArray<Field>): DataType.Definition => ({
  _tag: "Struct",
  id: id(name),
  name: `GitHub ${name}`,
  fields,
});
const enumeration = (name: string, variants: ReadonlyArray<string>): DataType.Definition => ({
  _tag: "Enum",
  id: id(name),
  name: `GitHub ${name}`,
  variants: variants.map((name) => ({ name, fields: [] })),
});

